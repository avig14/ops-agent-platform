"""Controlled vocabularies: failure reason codes and audit actions.
Failure codes are grouped by MAST-style category so every failure can be classified:
  specification | inter_agent | verification | infrastructure | policy | external
"""
from __future__ import annotations

from enum import Enum


class Reason(str, Enum):
    # LLM provider
    LLM_RATE_LIMIT = "LLM_RATE_LIMIT"
    LLM_OVERLOADED = "LLM_OVERLOADED"
    LLM_BILLING = "LLM_BILLING"
    LLM_AUTH = "LLM_AUTH"
    LLM_TIMEOUT = "LLM_TIMEOUT"
    LLM_BAD_REQUEST = "LLM_BAD_REQUEST"
    LLM_SCHEMA_INVALID = "LLM_SCHEMA_INVALID"
    LLM_SAFETY_BLOCK = "LLM_SAFETY_BLOCK"
    LLM_REFUSAL = "LLM_REFUSAL"
    LLM_TRUNCATED = "LLM_TRUNCATED"
    LLM_EMPTY = "LLM_EMPTY"
    LLM_CONTEXT_TOO_LONG = "LLM_CONTEXT_TOO_LONG"
    LLM_UNKNOWN = "LLM_UNKNOWN"
    # data sources
    DATA_UNAVAILABLE = "DATA_UNAVAILABLE"
    DATA_STALE = "DATA_STALE"
    DATA_PARTIAL = "DATA_PARTIAL"
    DATA_CONFLICT = "DATA_CONFLICT"
    DATA_MISSING = "DATA_MISSING"
    DATA_SCHEMA_DRIFT = "DATA_SCHEMA_DRIFT"
    DATA_AUTH = "DATA_AUTH"
    # output gates
    GATE_UNGROUNDED = "GATE_UNGROUNDED"
    GATE_NUMERIC_MISMATCH = "GATE_NUMERIC_MISMATCH"
    GATE_UNKNOWN_ENTITY = "GATE_UNKNOWN_ENTITY"
    GATE_BAD_ACTION = "GATE_BAD_ACTION"
    GATE_COMMS_NUMBER = "GATE_COMMS_NUMBER"
    GATE_COMMS_LEAK = "GATE_COMMS_LEAK"
    # safety / policy
    INJECTION_DETECTED = "INJECTION_DETECTED"
    CONFLICT_AGENTS = "CONFLICT_AGENTS"
    POLICY_UNAUTHORIZED = "POLICY_UNAUTHORIZED"
    POLICY_SOD = "POLICY_SOD"
    POLICY_THRESHOLD = "POLICY_THRESHOLD"
    # communication
    COMM_SEND_FAILED = "COMM_SEND_FAILED"
    COMM_BOUNCED = "COMM_BOUNCED"
    COMM_DELIVERY_UNKNOWN = "COMM_DELIVERY_UNKNOWN"
    COMM_DEAD = "COMM_DEAD"
    # infrastructure
    INFRA_CIRCUIT_OPEN = "INFRA_CIRCUIT_OPEN"
    INFRA_BUDGET_EXHAUSTED = "INFRA_BUDGET_EXHAUSTED"
    INFRA_AUDIT_WRITE_FAILED = "INFRA_AUDIT_WRITE_FAILED"
    INFRA_WORKER_LEASE_EXPIRED = "INFRA_WORKER_LEASE_EXPIRED"
    INFRA_TIMER_MISSED_CATCHUP = "INFRA_TIMER_MISSED_CATCHUP"
    # workflow
    WORKFLOW_DEADLINE_MISSED = "WORKFLOW_DEADLINE_MISSED"
    WORKFLOW_CANCELLED = "WORKFLOW_CANCELLED"
    WORKFLOW_REVISED = "WORKFLOW_REVISED"
    WORKFLOW_DUPLICATE = "WORKFLOW_DUPLICATE"
    WORKFLOW_CONCURRENCY_CONFLICT = "WORKFLOW_CONCURRENCY_CONFLICT"
    WORKFLOW_IDEMPOTENT_REPLAY = "WORKFLOW_IDEMPOTENT_REPLAY"
    WORKFLOW_CLOSURE_INCOMPLETE = "WORKFLOW_CLOSURE_INCOMPLETE"
    INGEST_UNSUPPORTED_ATTACHMENT = "INGEST_UNSUPPORTED_ATTACHMENT"
    INGEST_UNCLEAR_INTENT = "INGEST_UNCLEAR_INTENT"
    INGEST_MULTI_ISSUE = "INGEST_MULTI_ISSUE"
    INGEST_TOO_MANY_ISSUES = "INGEST_TOO_MANY_ISSUES"


CATEGORY: dict[str, str] = {}
for _r in Reason:
    n = _r.value
    if n.startswith(("GATE_", "LLM_SCHEMA", "LLM_REFUSAL", "LLM_TRUNCATED", "LLM_EMPTY", "DATA_CONFLICT")):
        CATEGORY[n] = "verification"
    elif n.startswith("INGEST_"):
        CATEGORY[n] = "specification"
    elif n.startswith(("CONFLICT_AGENTS", "INJECTION", "WORKFLOW_REVISED", "WORKFLOW_DUPLICATE")):
        CATEGORY[n] = "inter_agent"
    elif n.startswith(("POLICY_", "WORKFLOW_")):
        CATEGORY[n] = "policy"
    elif n.startswith("INFRA_"):
        CATEGORY[n] = "infrastructure"
    else:
        CATEGORY[n] = "external"


def category(reason: str | None) -> str | None:
    return CATEGORY.get(reason) if reason else None
